#[derive(Clone)]
struct Slot {
    generation: u64,
    run: Arc<Run>,
    dir: PathBuf,
}

type Controller = watch::Sender<Slot>;

pub async fn serve(
    listener: TcpListener,
    run: Arc<Run>,
    dir: PathBuf,
    demo_fixture: Option<SocketAddr>,
    bird_listen: SocketAddr,
    birds: u8,
    signal: impl Future<Output = Result<()>>,
) -> Result<(PathBuf, Arc<Frame>)> {
    let address = listener.local_addr()?;
    let hub = flock::Hub::bind(bird_listen).await?;
    let shutdown = CancellationToken::new();
    let rpc_stop = CancellationToken::new();
    let children = bird::spawn_demos(
        birds,
        &hub.endpoint,
        bird_listen,
        &dir,
        run.config(),
        shutdown.clone(),
    )?;
    println!("Dashboard: http://{address}");
    println!("Bird telemetry: {}", hub.endpoint);
    let telemetry = run.telemetry.clone();
    let (controller, mut runs) = watch::channel(Slot {
        generation: 1,
        run,
        dir,
    });
    let app = Router::new()
        .route("/", get(|| async { Html(report::DASHBOARD) }))
        .route(
            "/api/v1/health",
            get(|| async { Json(serde_json::json!({"status":"ok"})) }),
        )
        .route("/api/v1/runs/local", get(snapshot))
        .route("/api/v1/runs/local/start", post(start))
        .route("/api/v1/runs/local/check", post(check))
        .route("/api/v1/runs/local/stop", post(stop))
        .route("/api/v1/runs/local/next", post(next_run))
        .route(
            "/api/v1/runs/local/workload",
            post(load_yaml).layer(DefaultBodyLimit::max(MAX_CONFIG_BYTES)),
        )
        .route(
            "/api/v1/workload/example",
            get(move || async move {
                // Only a fixture address generated by the demo can appear in the public template.
                let yaml = match demo_fixture {
                    Some(addr) => STARTER_YAML.replacen(
                        "http://127.0.0.1:8081/mcp",
                        &format!("http://{addr}/mcp"),
                        1,
                    ),
                    None => STARTER_YAML.to_owned(),
                };
                (
                    [
                        (header::CONTENT_TYPE, "application/yaml"),
                        (
                            header::CONTENT_DISPOSITION,
                            "attachment; filename=\"starling.yaml\"",
                        ),
                    ],
                    yaml,
                )
            }),
        )
        .route("/api/v1/runs/local/live", get(upgrade))
        .route("/api/v1/runs/local/export", get(export))
        .with_state(controller)
        .merge(flock::routes(
            hub.flock.clone(),
            shutdown.clone(),
            hub.endpoint.clone(),
            birds,
        ))
        .layer(DefaultBodyLimit::max(2048))
        .layer(Extension(Arc::new(Semaphore::new(1))))
        .layer(middleware::from_fn_with_state(address, local_requests));
    let server = axum::serve(listener, app)
        .with_graceful_shutdown(shutdown.clone().cancelled_owned())
        .into_future();
    tokio::pin!(server);
    let lifecycle = async {
        tokio::pin!(signal);
        loop {
            let slot = runs.borrow_and_update().clone();
            let execute = slot.run.clone().execute(slot.dir.clone());
            tokio::pin!(execute);
            let frame = tokio::select! {
                result = &mut execute => result?,
                changed = runs.changed() => { changed?; continue; }
                event = &mut signal => {
                    event?; slot.run.stop();
                    return Ok((slot.dir, execute.await?));
                }
            };
            println!(
                "Report: {}. Dashboard remains open; Ctrl+C to exit.",
                slot.dir.join("index.html").display()
            );
            tokio::select! {
                biased;
                changed = runs.changed() => changed?,
                event = &mut signal => { event?; return Ok((slot.dir, frame)); }
            }
        }
    };
    let web = async {
        let _stop = shutdown.clone().drop_guard();
        tokio::select! {
            result = &mut server => { result?; bail!("dashboard stopped unexpectedly"); }
            result = lifecycle => { shutdown.cancel(); server.await?; result }
        }
    };
    let supervise = async {
        bird::supervise(children, shutdown.clone(), telemetry).await;
        rpc_stop.cancel();
        Ok(())
    };
    let (result, (), ()) = tokio::try_join!(web, hub.serve(rpc_stop.clone()), supervise)?;
    Ok(result)
}

async fn local_requests(State(addr): State<SocketAddr>, req: Request, next: Next) -> Response {
    let headers = req.headers();
    let host = headers
        .get(header::HOST)
        .and_then(|v| v.to_str().ok())
        .unwrap_or("");
    let host_ok = host == addr.to_string()
        || host == format!("localhost:{}", addr.port())
        || (addr.port() == 80
            && (host == "localhost" || host == addr.to_string().trim_end_matches(":80")));
    let foreign_origin = headers
        .get(header::ORIGIN)
        .is_some_and(|v| v.as_bytes() != format!("http://{host}").as_bytes());
    if !host_ok
        || foreign_origin
        || (*req.method() == Method::POST
            && headers.get("x-starling-control").is_none_or(|v| v != "1"))
    {
        return StatusCode::FORBIDDEN.into_response();
    }
    let mut response = next.run(req).await;
    response
        .headers_mut()
        .insert(header::CACHE_CONTROL, "no-store".parse().unwrap());
    response
        .headers_mut()
        .insert(header::X_FRAME_OPTIONS, "DENY".parse().unwrap());
    response
}

async fn snapshot(State(controller): State<Controller>) -> impl IntoResponse {
    Json((*controller.borrow().run.snapshot()).clone())
}

async fn start(
    State(controller): State<Controller>,
    Extension(gate): Extension<Arc<Semaphore>>,
    body: Bytes,
) -> Response {
    let Ok(_permit) = gate.try_acquire() else {
        return StatusCode::CONFLICT.into_response();
    };
    let options = if body.is_empty() {
        StartOptions::default()
    } else {
        match serde_json::from_slice(&body) {
            Ok(value) => value,
            Err(_) => {
                return (
                    StatusCode::BAD_REQUEST,
                    "Expected a JSON object with valid run settings and a supported MCP protocol.",
                )
                    .into_response();
            }
        }
    };
    match controller.borrow().run.start(options) {
        Ok(true) => StatusCode::ACCEPTED.into_response(),
        Ok(false) => StatusCode::CONFLICT.into_response(),
        Err(e) => (StatusCode::UNPROCESSABLE_ENTITY, e.to_string()).into_response(),
    }
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct CheckOptions {
    protocol: Option<Protocol>,
    endpoint: Option<String>,
    #[serde(default)]
    all_protocols: bool,
}

async fn check(
    State(controller): State<Controller>,
    Extension(gate): Extension<Arc<Semaphore>>,
    body: Bytes,
) -> Response {
    let Ok(_permit) = gate.try_acquire() else {
        return (StatusCode::CONFLICT, "Another check is in progress.").into_response();
    };
    let Ok(options) = serde_json::from_slice::<CheckOptions>(&body) else {
        return (StatusCode::BAD_REQUEST, "Invalid conformance selection.").into_response();
    };
    let run = controller.borrow().run.clone();
    if run.snapshot().view.status != crate::runner::Status::Ready {
        return (StatusCode::CONFLICT, "Checks require a ready run.").into_response();
    }
    let cfg = match run.config().clone().with_options(StartOptions {
        endpoint: options.endpoint,
        ..Default::default()
    }) {
        Ok(cfg) => cfg,
        Err(e) => return (StatusCode::UNPROCESSABLE_ENTITY, e.to_string()).into_response(),
    };
    let selection = Selection {
        protocol: options.protocol.into_iter().collect(),
        all_protocols: options.all_protocols,
    };
    match selection.for_config(&cfg) {
        Ok(revisions) => {
            Json(conformance::inspect(&cfg, &revisions, "local").await).into_response()
        }
        Err(e) => (StatusCode::UNPROCESSABLE_ENTITY, e.to_string()).into_response(),
    }
}

async fn stop(State(controller): State<Controller>) -> StatusCode {
    if controller.borrow().run.stop() {
        StatusCode::ACCEPTED
    } else {
        StatusCode::CONFLICT
    }
}

async fn next_run(State(controller): State<Controller>) -> Response {
    prepare_run(&controller, None)
}

async fn load_yaml(State(controller): State<Controller>, body: String) -> Response {
    match Config::from_yaml(&body, StartOptions::default()) {
        Ok(cfg) => prepare_run(&controller, Some(cfg)),
        Err(e) => (StatusCode::UNPROCESSABLE_ENTITY, e.to_string()).into_response(),
    }
}

fn prepare_run(controller: &Controller, workload: Option<Config>) -> Response {
    let mut status = StatusCode::CONFLICT;
    controller.send_if_modified(|slot| {
        let state = slot.run.snapshot().view.status;
        if !state.terminal() && !(state == crate::runner::Status::Ready && workload.is_some()) {
            return false;
        }
        let dir = if state.terminal() {
            report::reserve_in(slot.dir.parent().unwrap_or(&slot.dir))
        } else {
            Ok(slot.dir.clone())
        };
        match dir {
            Ok(dir) => {
                *slot = Slot {
                    generation: slot.generation + 1,
                    run: Run::new(
                        workload.unwrap_or_else(|| slot.run.config().clone()),
                        slot.run.telemetry.clone(),
                    ),
                    dir,
                };
                status = StatusCode::ACCEPTED;
                true
            }
            Err(_) => {
                slot.run
                    .telemetry
                    .event(Level::Error, "report_reservation_failed");
                status = StatusCode::INTERNAL_SERVER_ERROR;
                false
            }
        }
    });
    status.into_response()
}

async fn export(State(controller): State<Controller>) -> Response {
    let frame = controller.borrow().run.snapshot();
    if !frame.view.status.terminal() {
        return StatusCode::CONFLICT.into_response();
    }
    match report::html(&frame) {
        Ok(page) => (
            [(
                header::CONTENT_DISPOSITION,
                "attachment; filename=\"starling-report.html\"",
            )],
            Html(page),
        )
            .into_response(),
        Err(_) => StatusCode::INTERNAL_SERVER_ERROR.into_response(),
    }
}

async fn upgrade(State(controller): State<Controller>, ws: WebSocketUpgrade) -> Response {
    ws.max_message_size(1024)
        .max_frame_size(1024)
        .on_upgrade(move |socket| live(socket, controller.subscribe()))
}

#[derive(Serialize)]
struct MessageBody<'a> {
    generation: u64,
    #[serde(rename = "type")]
    kind: &'static str,
    #[serde(flatten)]
    overview: &'a Overview,
    series: &'a [Point],
}

async fn live(mut socket: WebSocket, mut runs: watch::Receiver<Slot>) {
    let subscribe = |slot: &Slot| (slot.generation, slot.run.subscribe());
    let (mut generation, mut feed) = subscribe(&runs.borrow_and_update());
    let mut previous = None;
    loop {
        let frame = feed.borrow_and_update().clone();
        let sequence = frame.view.sequence;
        // A slow reader skips publications rather than slowing down the runner.
        let (kind, from) = match previous {
            Some((seq, len)) if seq + 1 == sequence => ("tick", len),
            _ => ("snapshot", 0),
        };
        let body = MessageBody {
            generation,
            kind,
            overview: &frame.view,
            series: &frame.series[from..],
        };
        let text = serde_json::to_string(&body).expect("serializable frame");
        if !matches!(
            timeout(
                Duration::from_secs(5),
                socket.send(Message::Text(text.into()))
            )
            .await,
            Ok(Ok(()))
        ) {
            return;
        }
        previous = Some((sequence, frame.series.len()));
        loop {
            tokio::select! {
                biased;
                changed = runs.changed() => {
                    if changed.is_err() { return; }
                    (generation, feed) = subscribe(&runs.borrow_and_update());
                    previous = None;
                    break;
                }
                changed = feed.changed() => { if changed.is_err() { return; } break; }
                incoming = socket.recv() => match incoming {
                    Some(Ok(Message::Text(s))) if s == "snapshot" => { previous = None; break; }
                    Some(Ok(Message::Ping(_) | Message::Pong(_))) => (),
                    _ => return,
                }
            }
        }
    }
}
